namespace TrBlazeUI.Components.Drawer;

/// <summary>
/// Specifies the edge of the screen from which a drawer opens and slides in.
/// </summary>
public enum DrawerDirection
{
    /// <summary>
    /// The drawer opens from and is anchored to the top edge of the screen.
    /// </summary>
    Top,

    /// <summary>
    /// The drawer opens from and is anchored to the bottom edge of the screen.
    /// </summary>
    Bottom,

    /// <summary>
    /// The drawer opens from and is anchored to the left edge of the screen.
    /// </summary>
    Left,

    /// <summary>
    /// The drawer opens from and is anchored to the right edge of the screen.
    /// </summary>
    Right
}
