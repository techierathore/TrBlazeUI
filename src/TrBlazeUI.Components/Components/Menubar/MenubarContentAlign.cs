namespace TrBlazeUI.Components.Menubar;

/// <summary>
/// Specifies how menubar content is aligned relative to its trigger.
/// </summary>
public enum MenubarContentAlign
{
    /// <summary>Aligns the content to the start edge of the trigger.</summary>
    Start,
    /// <summary>Centers the content relative to the trigger.</summary>
    Center,
    /// <summary>Aligns the content to the end edge of the trigger.</summary>
    End
}
